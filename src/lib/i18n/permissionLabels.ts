export function getPermissionModuleLabel(
  module: string,
  language: Language,
): string {
  if (language === "ar") return ARABIC_MODULES[module] ?? "صلاحيات النظام";
  if (module === "schools") return "Customers, contacts & leads";
  return module.replaceAll("_", " ");
}

export function getPermissionLabel(
  code: string,
  fallback: string,
  language: Language,
): string {
  if (language !== "ar") return fallback;
  const [module, ...actionParts] = code.split(".");
  const action = actionParts.join("_");
  const moduleLabel = ARABIC_MODULES[module] ?? "النظام";
  const actionLabel = ARABIC_ACTIONS[action] ?? "استخدام الصلاحية";
  return `${moduleLabel} — ${actionLabel}`;
}
